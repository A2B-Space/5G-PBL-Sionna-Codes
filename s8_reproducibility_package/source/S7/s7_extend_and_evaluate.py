def parse_args():
    parser = argparse.ArgumentParser(
        description="Extend S6 with antenna-resolved paths and run S7.1-S7.5."
    )
    parser.add_argument(
        "--base-dir", type=Path, default=Path.home() / "sionna_project",
        help="Project directory containing s6_physical_layer_dataset/ and s4_blockage_geometry/."
    )
    return parser.parse_args()

EXPECTED_TX_ANTENNAS = 64
EXPECTED_BEAMS = 52
EXPECTED_CONDITIONS = ("unblocked", "blocked")
EPS = np.finfo(np.float64).tiny
PLOT_DPI = 200


# ---------------------------------------------------------------------------
# Utilities
# ---------------------------------------------------------------------------

def require_file(path: Path, purpose: str) -> None:
    if not path.is_file():
        raise FileNotFoundError(
            f"Required file not found: {path}\n"
            f"Purpose: {purpose}\n"
            "If the S4 path-coefficient archive is missing, rerun the corrected "
            "S4.1 exporter first. Do not fabricate or reconstruct 64-antenna "
            "path coefficients from the single-antenna CSV column."
        )


def db10(value):
    value = np.asarray(value, dtype=float)
    return 10.0 * np.log10(np.maximum(value, EPS))


def json_dump(path: Path, payload) -> None:
    path.write_text(json.dumps(payload, indent=2, allow_nan=False), encoding="utf-8")


def save_plot(fig, stem: str, pdf: PdfPages, generated: list[str]) -> None:
    png_path = PLOT_DIR / f"{stem}.png"
    pdf_path = PLOT_DIR / f"{stem}.pdf"
    fig.savefig(png_path, dpi=PLOT_DPI, bbox_inches="tight")
    fig.savefig(pdf_path, bbox_inches="tight")
    pdf.savefig(fig, bbox_inches="tight")
    plt.close(fig)
    for path in (png_path, pdf_path):
        if not path.exists() or path.stat().st_size == 0:
            raise RuntimeError(f"Plot was not saved correctly: {path}")
    generated.append(stem)


def assert_unique(df: pd.DataFrame, columns: list[str], label: str) -> None:
    if df.duplicated(columns).any():
        raise ValueError(f"Duplicate keys found in {label}: {columns}")


