# S7.5 - Adaptive tracking overhead/performance comparison
# ---------------------------------------------------------------------------

def evaluate_s7_5(data):
    tracking = data["tracking"].copy()
    methods = set(tracking["method"].astype(str))
    required = {
        "exhaustive_oracle", "hold_last_beam",
        "local_tracking", "adaptive_tracking",
    }
    if methods != required:
        raise ValueError(
            f"Unexpected tracking methods: {sorted(methods)}; expected {sorted(required)}."
        )

    rows = []
    for condition in EXPECTED_CONDITIONS:
        part = tracking[tracking["condition"].astype(str) == condition]
        adaptive = part[part["method"] == "adaptive_tracking"]
        adaptive_probes = int(adaptive["beams_probed"].sum())
        adaptive_mean_regret = float(adaptive["regret_db"].mean())

        for baseline_method in [
            "exhaustive_oracle", "hold_last_beam", "local_tracking"
        ]:
            baseline = part[part["method"] == baseline_method]
            baseline_probes = int(baseline["beams_probed"].sum())
            saved = baseline_probes - adaptive_probes
            rows.append({
                "condition": condition,
                "comparison_baseline": baseline_method,
                "baseline_total_probes": baseline_probes,
                "adaptive_total_probes": adaptive_probes,
                "probes_saved": saved,
                "probe_reduction_pct": (
                    100.0 * saved / baseline_probes if baseline_probes else np.nan
                ),
                "baseline_mean_regret_db": float(baseline["regret_db"].mean()),
                "adaptive_mean_regret_db": adaptive_mean_regret,
                "baseline_p95_regret_db": float(
                    np.percentile(baseline["regret_db"], 95)
                ),
                "adaptive_p95_regret_db": float(
                    np.percentile(adaptive["regret_db"], 95)
                ),
                "adaptive_maximum_regret_db": float(adaptive["regret_db"].max()),
                "adaptive_beam_switches": int(
                    adaptive["beam_switched"].astype(bool).sum()
                ),
                "adaptive_expanded_searches": int(
                    adaptive["expanded_search"].astype(bool).sum()
                ),
                "adaptive_fallback_full_sweeps": int(
                    adaptive["fallback_full_sweep"].astype(bool).sum()
                ),
            })

    per_snapshot = tracking[
        tracking["method"].isin(
            ["exhaustive_oracle", "hold_last_beam",
             "local_tracking", "adaptive_tracking"]
        )
    ][
        [
            "sample_id", "condition", "snapshot", "rx_x_m", "method",
            "selected_beam_id", "oracle_beam_id", "regret_db",
            "beams_probed", "beam_switched", "search_stage",
            "gain_drop_triggered", "expanded_search", "fallback_full_sweep",
        ]
    ].copy()

    return pd.DataFrame(rows), per_snapshot


