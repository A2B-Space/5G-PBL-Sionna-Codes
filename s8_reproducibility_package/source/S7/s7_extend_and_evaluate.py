def load_s6_inputs():
    require_file(S6_INPUT_DIR / "manifest.json", "S6 manifest")
    required_csvs = [
        "snapshot_metadata.csv",
        "path_records.csv",
        "interaction_records.csv",
        "beam_measurements.csv",
        "tracking_records.csv",
        "tracking_summary.csv",
        "beam_codebook.csv",
        "scene_objects.csv",
    ]
    for filename in required_csvs:
        require_file(S6_INPUT_DIR / filename, f"S6 input table {filename}")

    manifest = json.loads((S6_INPUT_DIR / "manifest.json").read_text())
    metadata = pd.read_csv(S6_INPUT_DIR / "snapshot_metadata.csv")
    paths = pd.read_csv(S6_INPUT_DIR / "path_records.csv")
    interactions = pd.read_csv(S6_INPUT_DIR / "interaction_records.csv")
    beams = pd.read_csv(S6_INPUT_DIR / "beam_measurements.csv")
    tracking = pd.read_csv(S6_INPUT_DIR / "tracking_records.csv")
    tracking_summary_original = pd.read_csv(S6_INPUT_DIR / "tracking_summary.csv")
    codebook = pd.read_csv(S6_INPUT_DIR / "beam_codebook.csv")

    for df, keys, label in [
        (metadata, ["sample_id"], "snapshot_metadata"),
        (paths, ["sample_id", "path_id"], "path_records"),
        (interactions, ["sample_id", "path_id", "interaction_order"],
         "interaction_records"),
        (beams, ["sample_id", "beam_id"], "beam_measurements"),
        (tracking, ["sample_id", "method"], "tracking_records"),
    ]:
        assert_unique(df, keys, label)

    if set(metadata["condition"].astype(str)) != set(EXPECTED_CONDITIONS):
        raise ValueError("S6 metadata does not contain exactly unblocked/blocked.")
    if metadata["sample_id"].isna().any() or metadata["sample_id"].duplicated().any():
        raise ValueError("S6 sample IDs are null or duplicated.")

    expected_samples = len(EXPECTED_CONDITIONS) * metadata["snapshot"].nunique()
    if len(metadata) != expected_samples:
        raise ValueError(
            f"Expected {expected_samples} samples, found {len(metadata)}."
        )

    if len(codebook) != EXPECTED_BEAMS:
        raise ValueError(f"Expected {EXPECTED_BEAMS} codebook rows.")

    required_path_cols = {
        "sample_id", "condition", "snapshot", "path_id", "delay_s",
        "path_coefficient_real", "path_coefficient_imag",
        "path_coefficient_reference_tx_antenna",
    }
    if not required_path_cols.issubset(paths.columns):
        raise ValueError(
            f"path_records.csv missing columns: "
            f"{sorted(required_path_cols - set(paths.columns))}"
        )

    return {
        "manifest": manifest,
        "metadata": metadata,
        "paths": paths,
        "interactions": interactions,
        "beams": beams,
        "tracking": tracking,
        "tracking_summary_original": tracking_summary_original,
        "codebook": codebook,
    }


