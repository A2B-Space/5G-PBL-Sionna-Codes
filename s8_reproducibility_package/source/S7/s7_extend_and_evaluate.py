# S7.3 - Multipath and interaction characterization
# ---------------------------------------------------------------------------

def evaluate_s7_3(data):
    paths = data["paths"].copy()
    interactions = data["interactions"].copy()

    if interactions.empty:
        interaction_summary = pd.DataFrame(
            columns=["condition", "interaction_type", "event_count",
                     "unique_interacting_paths", "unique_snapshots"]
        )
    else:
        interactions = interactions.copy()
        interactions["_path_key"] = (
            interactions["sample_id"].astype(str) + "::"
            + interactions["path_id"].astype(str)
        )
        interaction_summary = (
            interactions.groupby(["condition", "interaction_type"], as_index=False)
            .agg(
                event_count=("interaction_code", "size"),
                unique_interacting_paths=("_path_key", "nunique"),
                unique_snapshots=("snapshot", "nunique"),
                mean_interaction_order=("interaction_order", "mean"),
                unique_scene_objects=("object_id", "nunique"),
            )
        )

    # Path-level classification: direct LOS, or interacting path grouped by
    # the set of interaction types it contains. This is descriptive only.
    path_type = (
        interactions.groupby(["sample_id", "path_id"])["interaction_type"]
        .agg(lambda x: "+".join(sorted(set(map(str, x)))))
        .rename("interaction_type_set")
        .reset_index()
    )
    path_class = paths.merge(
        path_type, on=["sample_id", "path_id"], how="left", validate="one_to_one"
    )
    path_class["interaction_type_set"] = path_class[
        "interaction_type_set"
    ].fillna("direct_no_interaction")

    delay_summary = (
        path_class.groupby(["condition", "interaction_type_set"], as_index=False)
        .agg(
            path_count=("path_id", "size"),
            mean_delay_ns=("delay_ns", "mean"),
            median_delay_ns=("delay_ns", "median"),
            p95_delay_ns=("delay_ns", lambda x: float(np.percentile(x, 95))),
            mean_interaction_count=("interaction_count", "mean"),
            unique_snapshots=("snapshot", "nunique"),
        )
    )

    path_order = (
        interactions.groupby(["sample_id", "path_id"], as_index=False)
        .agg(interaction_depth=("interaction_order", "count"))
    )
    depth_summary = (
        path_order.groupby("interaction_depth", as_index=False)
        .size()
        .rename(columns={"size": "number_of_paths"})
    )

    return interaction_summary, delay_summary, depth_summary


