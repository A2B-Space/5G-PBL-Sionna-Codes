# S7.4 - Beam selection quality
# ---------------------------------------------------------------------------

def evaluate_s7_4(data):
    tracking = data["tracking"].copy()
    tracking["beam_matches_oracle"] = (
        tracking["selected_beam_id"].astype(int)
        == tracking["oracle_beam_id"].astype(int)
    )

    summary = (
        tracking.groupby(["condition", "method"], as_index=False)
        .agg(
            snapshots=("snapshot", "size"),
            total_beam_probes=("beams_probed", "sum"),
            mean_beams_probed=("beams_probed", "mean"),
            mean_regret_db=("regret_db", "mean"),
            median_regret_db=("regret_db", "median"),
            p95_regret_db=("regret_db", lambda x: float(np.percentile(x, 95))),
            maximum_regret_db=("regret_db", "max"),
            oracle_beam_match_pct=("beam_matches_oracle",
                                   lambda x: 100.0 * float(np.mean(x))),
            beam_switches=("beam_switched", "sum"),
            full_sweeps=("is_full_sweep", "sum"),
        )
    )
    per_snapshot = tracking[
        [
            "sample_id", "condition", "snapshot", "rx_x_m", "method",
            "selected_beam_id", "oracle_beam_id", "selected_gain_db",
            "oracle_gain_db", "regret_db", "beam_matches_oracle",
            "beams_probed", "beam_switched", "search_stage",
        ]
    ].copy()
    return summary, per_snapshot


