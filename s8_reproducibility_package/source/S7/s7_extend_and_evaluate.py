#!/usr/bin/env python3
"""
S6 ANTENNA-RESOLVED PATH-COEFFICIENT EXTENSION + S7.1-S7.5 ANALYSIS

Purpose
-------
1. Extend the S6 dataset with all 64 TX-antenna path coefficients for every
   valid ray-traced path.
2. Verify that the coefficient archive is aligned to S6 sample IDs/path IDs
   and that TX antenna 0 agrees with the scalar coefficients in path_records.csv.
3. Run S7.1-S7.5 descriptive physical-layer and beam-management evaluations.
4. Save machine-readable tables, PNG/PDF plots, a combined PDF report,
   validation results, and an interpretation report.

Input directory structure
-------------------------
~/sionna_project/
    s6_physical_layer_dataset/
    s4_blockage_geometry/
        s4_path_coefficients.npz

The s4_path_coefficients.npz file is generated by the corrected S4.1
exporter (s4_1_path_geometry_export_s6_fixed.py). It contains:
    path_coefficients_complex [condition, snapshot, TX antenna, path index]
    path_counts [condition, snapshot]
    condition_names, snapshot_ids, tx_antenna_ids

Outputs
-------
~/sionna_project/
    s6_physical_layer_dataset_extended/
        [copy of S6 dataset]
        path_antenna_coefficients.csv
        path_coefficients_antenna_resolved.npz
        updated manifest/data dictionary/README/validation
    s7_performance_evaluation/
        s7_1_channel_characteristics.csv
        s7_2_blockage_paired_comparison.csv
        s7_3_interaction_summary.csv
        s7_3_path_delay_summary.csv
        s7_4_beam_selection_summary.csv
        s7_4_beam_selection_per_snapshot.csv
        s7_5_tracking_comparison.csv
        s7_5_tracking_per_snapshot.csv
        plots/*.png and plots/*.pdf
        s7_performance_report.pdf
        s7_findings.md
        s7_validation.txt
        s7_manifest.json

Run
---
cd ~/sionna_project
source .venv/bin/activate
python s7_extend_and_evaluate.py

Dependencies: numpy, pandas, matplotlib
No Sionna/Mitsuba/GPU execution is required by this script.

Important interpretation limits
-------------------------------
- Current experiment: one scene, one spatial quasi-static trajectory, 11
  positions, two paired environment conditions.
- The 64-element path coefficients are Sionna Paths.a passband coefficients.
  They are not calibrated received powers.
- Channel vectors and beam gains are single-baseband-frequency-offset data,
  not a wideband CFR.
- Doppler is zero in this static-position experiment; no Doppler tracking claim.
- Statistical summaries are descriptive. No population-level significance
  or generalization claim is made from one trajectory.
- "Blocked" means the added cuboid is present. Original-scene NLOS can occur
  even when that cuboid is absent.
- Beam gain is dimensionless |h^T w|^2, not watts or dBm.
"""

